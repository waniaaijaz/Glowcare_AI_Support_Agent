def list_conversations(limit: int = 20):
    """Most recent chats with message counts and the first customer question."""
    query = """
        SELECT c.conversation_id, c.status, c.started_at,
               COUNT(m.message_id) AS message_count,
               MAX(m.created_at) AS last_message_at,
               (ARRAY_AGG(m.content ORDER BY m.message_id)
                    FILTER (WHERE m.sender = 'customer'))[1] AS first_question
        FROM conversations c
        JOIN messages m ON m.conversation_id = c.conversation_id
        GROUP BY c.conversation_id
        ORDER BY MAX(m.created_at) DESC
        LIMIT %s;
    """
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(query, (limit,))
            return [dict(r) for r in cur.fetchall()]


